/**
 * Deterministic pseudo-random numbers for mock data — the same seed string
 * always yields the same sequence, so seeded history is stable across reloads
 * and identical in every tab.
 */

/** 32-bit FNV-1a hash of a string. */
export function hashString(value: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < value.length; i++) {
    h ^= value.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

export interface Rng {
  /** Float in [0, 1). */
  next(): number;
  /** Integer in [min, max], both inclusive. */
  int(min: number, max: number): number;
  /** `true` with probability `p`. */
  chance(p: number): boolean;
  pick<T>(items: ReadonlyArray<T>): T;
}

/** Mulberry32 generator seeded from a string. */
export function createRng(seed: string): Rng {
  let a = hashString(seed);
  const next = (): number => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
  return {
    next,
    int: (min, max) => min + Math.floor(next() * (max - min + 1)),
    chance: (p) => next() < p,
    pick: (items) => items[Math.floor(next() * items.length)],
  };
}
